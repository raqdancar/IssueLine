-- Link legacy timeline rows to their canonical cached issue when metadata still contains a GCD id.
with timeline_gcd_ids as (
  select
    timeline.id,
    timeline.hero_api_id,
    case
      when coalesce(timeline.metadata ->> 'gcdIssueId', timeline.metadata ->> 'gcd_issue_id') ~ '^[0-9]{1,10}$'
        then coalesce(timeline.metadata ->> 'gcdIssueId', timeline.metadata ->> 'gcd_issue_id')::bigint
      else null
    end as gcd_issue_id
  from public.hero_timelines as timeline
  where timeline.hero_issue_id is null
)
update public.hero_timelines as timeline
set hero_issue_id = issue.id
from timeline_gcd_ids as legacy
join public.hero_issues as issue
  on issue.hero_api_id = legacy.hero_api_id
 and issue.gcd_issue_id = legacy.gcd_issue_id
where timeline.id = legacy.id
  and legacy.gcd_issue_id is not null;

